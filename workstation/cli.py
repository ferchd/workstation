def base_paths() -> tuple[Path, Path, Path]:
    home = Path.home()
    config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config") / "workstation"
    state = Path(os.environ.get("XDG_STATE_HOME") or home / ".local/state") / "workstation"
    binpath = home / ".local/bin"
    return config, state, binpath


def json_profile(p: dict) -> str:
    return json.dumps(p, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def print_plan(p: dict):
    h, r = p["hardware"], p["recommendations"]
    print(f"SO: {h['os']['pretty_name']} | Kernel: {h['os']['kernel']}")
    print(f"CPU: {h['cpu']['model']} ({h['cpu']['logical_threads']} hilos)")
    print(f"RAM: {h['memory']['total_mib']/1024:.1f} GiB")
    d = h["storage"]["root"]
    print(f"Disco raíz: {d['size_gib']} GiB ({d['free_gib']} GiB libres), {h['storage']['root_fs']}")
    print(f"Entorno: {h['machine']['desktop_session']} | VM: {h['machine']['vm']} | portátil: {h['machine']['laptop']}")
    print(f"ZRAM activo: {h['current_system']['zram_active']}; configurado: {h['current_system']['zram_configured']}")
    print(f"Perfil: {r['tier']} | compilación: {r['build_jobs']} jobs | contenedores simultáneos sugeridos: {r['container_parallel_limit_advisory']}")
    print(f"Límite propuesto journal (OPCIONAL): {r['journal_limit_mib']} MiB")
    print("Sin tocar: " + ", ".join(r["preserve_cachyos"]))
    for w in r["warnings"]:
        print("AVISO: " + w)


def mkdir_private(p: Path) -> None:
    p.mkdir(parents=True, exist_ok=True)
    p.chmod(0o700)


def do_scan(p: dict, output: str | None):
    _, state, _ = base_paths()
    outfile = Path(output).expanduser() if output else state / "profile.json"
    mkdir_private(outfile.parent)
    outfile.write_text(json_profile(p), encoding="utf-8")
    outfile.chmod(0o600)
    print_plan(p)
    print(f"\nPerfil JSON escrito en: {outfile}")


def create_wrapper() -> str:
    return """#!/usr/bin/env sh
# Workstation wrapper: use *reviewed*, per-machine compile concurrency.
set -eu
[ \"$#\" -gt 0 ] || { echo 'Uso: ws-build <comando> [args...]' >&2; exit 2; }
CONFIG=\"${XDG_CONFIG_HOME:-$HOME/.config}/workstation/build.env\"
if [ -r \"$CONFIG\" ]; then
    # Archivo generado y propiedad del usuario; no lo cargues de fuentes no confiables.
    . \"$CONFIG\"
fi
export MAKEFLAGS CMAKE_BUILD_PARALLEL_LEVEL CARGO_BUILD_JOBS
exec \"$@\"
"""


def live_environment() -> bool:
    """Do not configure the ephemeral installer image, even if ID=cachyos."""
    cmdline = ""
    try:
        cmdline = Path("/proc/cmdline").read_text(encoding="utf-8", errors="ignore")
    except OSError:
        pass
    return (Path("/run/archiso").exists() or "archisobasedir=" in cmdline
            or "boot=live" in cmdline or "cow_spacesize=" in cmdline)


def do_apply(p: dict):
    if os.geteuid() == 0:
        sys.exit("No ejecutes como root; se modifica solo la configuración de tu usuario.")
    if p["hardware"]["os"]["id"] != "cachyos":
        sys.exit("Se niega la aplicación fuera de CachyOS. Ejecuta 'scan' para inspección.")
    if live_environment():
        sys.exit("Se detectó un entorno Live: instala e inicia CachyOS en disco antes de aplicar ajustes.")
    config, state, binpath = base_paths()
    mkdir_private(config)
    mkdir_private(state)
    binpath.mkdir(parents=True, exist_ok=True)
    jobs = p["recommendations"]["build_jobs"]
    files = {
        config / "build.env": f"# Generated by Workstation. Review before sourcing.\nMAKEFLAGS='-j{jobs}'\nCMAKE_BUILD_PARALLEL_LEVEL='{jobs}'\nCARGO_BUILD_JOBS='{jobs}'\n",
        binpath / "ws-build": create_wrapper(),
    }
    backups = state / "backups" / dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    mkdir_private(backups)
    manifest = []
    for dest, data in files.items():
        previous = dest.read_bytes() if dest.exists() else None
        if previous == data.encode():
            print(f"Sin cambios: {dest}")
            continue
        item = {"destination": str(dest), "existed": previous is not None}
        if previous is not None:
            backup = backups / ("file-" + str(len(manifest)))
            backup.write_bytes(previous)
            backup.chmod(0o600)
            item["backup"] = str(backup)
        dest.write_text(data, encoding="utf-8")
        dest.chmod(0o755 if dest.name == "ws-build" else 0o600)
        item["created_hash"] = hashlib.sha256(data.encode("utf-8")).hexdigest()
        manifest.append(item)
        print(f"Generado: {dest}")
    if manifest:
        (backups / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"Copia para reversión: {backups}")
    print("Usa: ws-build make, ws-build cargo build o ws-build cmake --build build")
    print("Sin cambios en sysctl, swap, zram, governor ni servicios del sistema.")


def do_rollback(yes: bool):
    if os.geteuid() == 0:
        sys.exit("No ejecutes rollback como root.")
    config, state, binpath = base_paths()
    backup_root = state / "backups"
    manifests = sorted(backup_root.glob("*/manifest.json"), reverse=True)
    if not manifests:
        print("No se encontraron aplicaciones anteriores para revertir.")
        return
    manifest_path = manifests[0]
    items = json.loads(manifest_path.read_text(encoding="utf-8"))
    allowed = {str(config / "build.env"), str(binpath / "ws-build")}
    print("Se propone revertir el último cambio del perfil:", manifest_path.parent)
    for item in items:
        print("-", item["destination"])
    if not yes:
        print("Vista previa. Ejecuta: python3 ws.py rollback --yes")
        return
    for item in items:
        dest = Path(item["destination"])
        if str(dest) not in allowed:
            print("Ignorando ruta no permitida:", dest)
            continue
        if not dest.is_file() or hashlib.sha256(dest.read_bytes()).hexdigest() != item.get("created_hash"):
            print("Modificado después de aplicar; no se toca:", dest)
            continue
        if item.get("existed"):
            backup = Path(item.get("backup", ""))
            if not backup.is_file() or not backup.is_relative_to(manifest_path.parent):
                print("Respaldo inexistente/inválido; sin cambios:", dest)
                continue
            dest.write_bytes(backup.read_bytes())
            dest.chmod(0o755 if dest.name == "ws-build" else 0o600)
        else:
            dest.unlink()
        print("Restaurado:", dest)
    manifest_path.rename(manifest_path.with_suffix(".restored.json"))


def do_tools(module: str, yes: bool, p: dict):
    if os.geteuid() == 0:
        sys.exit("No ejecutes la instalación como root: usa tu usuario con sudo.")
    if p["hardware"]["os"]["id"] != "cachyos":
        sys.exit("La instalación de herramientas se limita a CachyOS.")
    if live_environment():
        sys.exit("No se instalan paquetes en el entorno Live: inicia CachyOS instalado.")
    label, packages = MODULES[module]
    print(f"Módulo: {module} — {label}\nPaquetes: {' '.join(packages)}")
    if module == "xfce-style" and "XFCE" not in p["hardware"]["machine"]["desktop_session"].upper():
        print("AVISO: no se detecta Xfce; instalar temas NO cambia el escritorio activo.")
    if not yes:
        print("Solo vista previa. Para instalar: python3 ws.py tools", module, "--yes")
        return
    print("Ejecutando actualización COMPLETA e instalación con pacman. Puede solicitar tu contraseña sudo.")
    subprocess.run(["sudo", "pacman", "-Syu", "--needed", *packages], check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description="Workstation v4: CachyOS seguro y personalizable")
    sub = parser.add_subparsers(dest="action", required=True)
    scan = sub.add_parser("scan", help="Inspeccionar hardware y guardar perfil JSON sin root")
    scan.add_argument("--output", default=None, help="Ruta personalizada de JSON")
    sub.add_parser("plan", help="Mostrar decisiones propuestas, sin escribir nada")
    sub.add_parser("apply", help="Crear ajustes reversibles de compilación en HOME")
    sub.add_parser("refresh", help="Reexaminar hardware, escribir JSON y actualizar ajustes de usuario")
    rollback = sub.add_parser("rollback", help="Revertir último cambio si archivos no fueron modificados")
    rollback.add_argument("--yes", action="store_true")
    style = sub.add_parser("style", help="Vista previa, aplicar o restaurar apariencia completa de Xfce")
    style_action = style.add_mutually_exclusive_group()
    style_action.add_argument("--apply", action="store_true", help="Aplica el perfil Sage sobre Xfce/X11")
    style_action.add_argument("--restore", action="store_true", help="Restaura el último perfil visual")
    tools = sub.add_parser("tools", help="Previsualizar o instalar paquetes por módulo")
    tools.add_argument("module", choices=sorted(MODULES))
    tools.add_argument("--yes", action="store_true", help="Ejecutar pacman -Syu --needed")
    args = parser.parse_args()
    p = profile()
    if args.action == "plan":
        print_plan(p)
        print("\nMódulos disponibles: " + ", ".join(sorted(MODULES)))
        print("plan no escribe archivos ni instala paquetes.")
    elif args.action == "scan":
        do_scan(p, args.output)
    elif args.action == "apply":
        do_apply(p)
    elif args.action == "refresh":
        if p["hardware"]["os"]["id"] != "cachyos" or live_environment():
            sys.exit("Refresh solo admite CachyOS instalado, fuera del entorno Live.")
        do_scan(p, None)
        do_apply(p)
    elif args.action == "style":
        helper = Path(__file__).resolve().parents[1] / "scripts/15-escritorio-completo.py"
        mode = "--apply" if args.apply else "--restore" if args.restore else "--plan"
        subprocess.run([sys.executable, str(helper), mode], check=True)
    elif args.action == "tools":
        do_tools(args.module, args.yes, p)
    elif args.action == "rollback":
        do_rollback(args.yes)


if __name__ == "__main__":
    main()
